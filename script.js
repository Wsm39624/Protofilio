let currentLang = 'en';

function toggleLanguage() {
    currentLang = currentLang === 'en' ? 'ar' : 'en';

    document.documentElement.dir = currentLang === 'en' ? 'ltr' : 'rtl';
    document.documentElement.lang = currentLang;

    const langBtnText = currentLang === 'en' ? 'العربية' : 'English';
    document.getElementById('lang-text').innerText = langBtnText;

    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[currentLang][key]) {
            el.innerText = translations[currentLang][key];
        }
    });

    document.title = translations[currentLang].title;
}

document.addEventListener('DOMContentLoaded', () => {
    const sections = document.querySelectorAll('section, header');
    const navLinks = document.querySelectorAll('.nav-links a');

    window.addEventListener('scroll', () => {
        let current = '';

        sections.forEach(section => {
            const sectionTop = section.offsetTop;
            if (pageYOffset >= (sectionTop - window.innerHeight / 2)) {
                current = section.getAttribute('id');
            }
        });

        if ((window.innerHeight + window.scrollY) >= document.body.offsetHeight - 10) {
            current = 'contact';
        }

        navLinks.forEach(link => {
            link.classList.remove('active');

            if (link.getAttribute('href').includes(current)) {
                link.classList.add('active');
            }
        });
    });

    // Mobile nav toggle
    const navToggle = document.getElementById('nav-toggle');
    const navRight = document.getElementById('nav-right');

    if (navToggle && navRight) {
        navToggle.addEventListener('click', () => {
            const isOpen = navRight.classList.toggle('open');
            navToggle.classList.toggle('open', isOpen);
            navToggle.setAttribute('aria-expanded', isOpen ? 'true' : 'false');
        });

        navLinks.forEach(link => {
            link.addEventListener('click', () => {
                navRight.classList.remove('open');
                navToggle.classList.remove('open');
                navToggle.setAttribute('aria-expanded', 'false');
            });
        });
    }

    // Toggle Flip on Click / Tap for Experience Card (PC & Mobile)
    const expCard = document.getElementById('expCard');
    if (expCard) {
        expCard.addEventListener('click', () => {
            expCard.classList.toggle('flipped');
        });
    }

    // Toggle Flip on Click / Tap for Project Cards (PC & Mobile)
    const projCards = document.querySelectorAll('.clickable-proj-card');
    projCards.forEach(card => {
        card.addEventListener('click', () => {
            card.classList.toggle('flipped');
        });
    });

    // Certificate lightbox
    const lightbox = document.getElementById('cert-lightbox');
    const lightboxImg = document.getElementById('cert-lightbox-img');
    const lightboxClose = document.querySelector('.cert-lightbox-close');
    const certCards = document.querySelectorAll('.cert-card');

    certCards.forEach(card => {
        card.addEventListener('click', () => {
            const imgSrc = card.getAttribute('data-img');
            lightboxImg.src = imgSrc;
            lightbox.classList.add('open');
        });
    });

    // فتح الشهادة عند الضغط على زر View Certificate في قسم الخبرة المهنية
    const certTriggerBtns = document.querySelectorAll('.cert-trigger-btn');
    certTriggerBtns.forEach(btn => {
        btn.addEventListener('click', (e) => {
            e.stopPropagation();
            const imgSrc = btn.getAttribute('data-img');
            if (lightboxImg && lightbox) {
                lightboxImg.src = imgSrc;
                lightbox.classList.add('open');
            }
        });
    });

    function closeLightbox() {
        lightbox.classList.remove('open');
        lightboxImg.src = '';
    }

    if (lightboxClose) {
        lightboxClose.addEventListener('click', closeLightbox);
    }

    if (lightbox) {
        lightbox.addEventListener('click', (e) => {
            if (e.target === lightbox) {
                closeLightbox();
            }
        });
    }

    document.addEventListener('keydown', (e) => {
        if (e.key === 'Escape') {
            closeLightbox();
        }
    });

    // Mouse Swaying Effect for ID Badge
    const badge = document.getElementById('idBadge');

    if (badge) {
        badge.addEventListener('mousemove', (e) => {
            const rect = badge.getBoundingClientRect();
            const centerX = rect.left + rect.width / 2;
            const topY = rect.top;

            const deltaX = e.clientX - centerX;
            const deltaY = e.clientY - topY;

            const rotateZ = (deltaX / rect.width) * 10;
            const rotateX = -(deltaY / rect.height) * 5;

            badge.style.transform = `perspective(1000px) rotateZ(${rotateZ}deg) rotateX(${rotateX}deg)`;
        });

        badge.addEventListener('mouseleave', () => {
            badge.style.transform = 'perspective(1000px) rotateZ(0deg) rotateX(0deg)';
        });
    }

    // Award Image Slider Logic
    const slides = document.querySelectorAll('#awardSlider .slide');
    const dots = document.querySelectorAll('#sliderDots .dot');
    const btnNext = document.getElementById('sliderNext');
    const btnPrev = document.getElementById('sliderPrev');
    const sliderContainer = document.getElementById('awardSlider');

    if (slides.length > 0) {
        let currentSlide = 0;
        let slideInterval = null;
        const autoPlayDelay = 15000;

        function showSlide(index) {
            slides.forEach((slide, i) => {
                slide.classList.toggle('active', i === index);
            });
            dots.forEach((dot, i) => {
                dot.classList.toggle('active', i === index);
            });
            currentSlide = index;
        }

        function nextSlide() {
            let nextIndex = (currentSlide + 1) % slides.length;
            showSlide(nextIndex);
        }

        function prevSlide() {
            let prevIndex = (currentSlide - 1 + slides.length) % slides.length;
            showSlide(prevIndex);
        }

        function startAutoPlay() {
            stopAutoPlay();
            slideInterval = setInterval(nextSlide, autoPlayDelay);
        }

        function stopAutoPlay() {
            if (slideInterval) {
                clearInterval(slideInterval);
            }
        }

        if (btnNext) {
            btnNext.addEventListener('click', () => {
                nextSlide();
                startAutoPlay();
            });
        }

        if (btnPrev) {
            btnPrev.addEventListener('click', () => {
                prevSlide();
                startAutoPlay();
            });
        }

        dots.forEach(dot => {
            dot.addEventListener('click', (e) => {
                const index = parseInt(e.target.getAttribute('data-slide'));
                if (!isNaN(index)) {
                    showSlide(index);
                    startAutoPlay();
                }
            });
        });

        if (sliderContainer) {
            sliderContainer.addEventListener('mouseenter', stopAutoPlay);
            sliderContainer.addEventListener('mouseleave', startAutoPlay);
        }

        showSlide(0);
        startAutoPlay();
    }

    // Formspree AJAX Submission for seamless UX
    const contactForm = document.getElementById('contact-form');
    const formStatus = document.getElementById('form-status');
    const submitBtn = document.getElementById('form-submit-btn');

    if (contactForm) {
        contactForm.addEventListener('submit', async (e) => {
            e.preventDefault();
            const data = new FormData(contactForm);
            
            submitBtn.disabled = true;
            submitBtn.style.opacity = '0.7';

            try {
                const response = await fetch(contactForm.action, {
                    method: contactForm.method,
                    body: data,
                    headers: {
                        'Accept': 'application/json'
                    }
                });

                if (response.ok) {
                    formStatus.className = 'form-status success';
                    formStatus.innerText = translations[currentLang].formSuccess;
                    contactForm.reset();
                } else {
                    const responseData = await response.json();
                    formStatus.className = 'form-status error';
                    if (Object.hasOwn(responseData, 'errors')) {
                        formStatus.innerText = responseData["errors"].map(error => error["message"]).join(", ");
                    } else {
                        formStatus.innerText = translations[currentLang].formError;
                    }
                }
            } catch (error) {
                formStatus.className = 'form-status error';
                formStatus.innerText = translations[currentLang].formError;
            } finally {
                submitBtn.disabled = false;
                submitBtn.style.opacity = '1';
                setTimeout(() => {
                    formStatus.innerText = '';
                    formStatus.className = 'form-status';
                }, 6000);
            }
        });
    }
});